"""
Karaoke ASS (Advanced SubStation Alpha) Exporter and FFmpeg Video Generator.

Standard Aegisub ASS v4.00+ implementation adhering to:
https://aegisub.org/docs/latest/ass_tags/

Supports word-level karaoke timing tags (\\k, \\kf, \\ko) with centisecond durations (1 cs = 10 ms),
UTF-8 Mongolian Cyrillic, customizable primary/secondary colors, styles, and optional
FFmpeg video burning.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from typing import Any, Dict, List, Optional


def find_system_or_bundled_ffmpeg() -> Optional[str]:
    """Find a working ffmpeg binary from tools/ffmpeg or system PATH."""
    bundled_path = os.path.join(os.path.dirname(__file__), "tools", "ffmpeg", "ffmpeg.exe")
    if os.path.isfile(bundled_path) and os.access(bundled_path, os.X_OK):
        return bundled_path

    # Check system PATH
    sys_path = shutil.which("ffmpeg")
    if sys_path:
        return sys_path

    return None


def is_ffmpeg_available() -> bool:
    """Return True if a functional FFmpeg executable is located."""
    return find_system_or_bundled_ffmpeg() is not None


def format_ass_timestamp(seconds: float) -> str:
    """
    Format seconds into ASS timestamp format: H:MM:SS.cs (centiseconds).
    Example: 83.456 -> 0:01:23.46
    """
    if seconds < 0:
        seconds = 0.0

    total_centis = int(round(seconds * 100))
    cs = total_centis % 100
    total_seconds = total_centis // 100
    s = total_seconds % 60
    total_minutes = total_seconds // 60
    m = total_minutes % 60
    h = total_minutes // 60

    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def seconds_to_centiseconds(seconds: float) -> int:
    """Convert a duration in seconds into ASS centiseconds (1 cs = 10 ms)."""
    return max(1, int(round(seconds * 100)))


def generate_karaoke_ass(
    segments: List[Dict[str, Any]],
    title: str = "Voice Karaoke",
    script_author: str = "VOICE App Studio",
    play_res_x: int = 1920,
    play_res_y: int = 1080,
    font_name: str = "Arial",
    font_size: int = 48,
    primary_color: str = "&H0000FFFF",    # Yellow in BGR &HAABBGGRR
    secondary_color: str = "&H00FFFFFF",  # White
    outline_color: str = "&H00101010",    # Dark Grey
    back_color: str = "&H60000000",       # Semi-transparent Shadow
    karaoke_tag: str = "\\kf",            # \\k, \\K, or \\kf (smooth fill)
) -> str:
    """
    Generate standard Aegisub-compliant ASS content.

    Segments can contain word timestamps:
    [
        {
            "start": 1.2,
            "end": 4.5,
            "text": "Сайн байна уу",
            "words": [
                {"word": "Сайн", "start": 1.2, "end": 2.0},
                {"word": "байна", "start": 2.1, "end": 3.0},
                {"word": "уу", "start": 3.1, "end": 4.5}
            ]
        }
    ]
    """
    lines: List[str] = [
        "[Script Info]",
        f"; Script generated by {script_author}",
        f"Title: {title}",
        "ScriptType: v4.00+",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        f"PlayResX: {play_res_x}",
        f"PlayResY: {play_res_y}",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        f"Style: Default,{font_name},{font_size},{primary_color},{secondary_color},{outline_color},{back_color},1,0,0,0,100,100,0,0,1,3,2,2,40,40,60,1",
        f"Style: Karaoke,{font_name},{font_size + 4},{primary_color},{secondary_color},{outline_color},{back_color},1,0,0,0,100,100,1,0,1,3.5,2.5,2,40,40,70,1",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]

    for seg in segments:
        seg_start = float(seg.get("start", 0.0))
        seg_end = float(seg.get("end", seg_start + 1.0))
        words = seg.get("words", [])

        start_str = format_ass_timestamp(seg_start)
        end_str = format_ass_timestamp(seg_end)

        if words and isinstance(words, list):
            # Generate word-level karaoke tags
            karaoke_text_parts: List[str] = []
            prev_end = seg_start

            for w in words:
                w_start = float(w.get("start", prev_end))
                w_end = float(w.get("end", w_start + 0.2))
                w_word = str(w.get("word", "")).strip()
                if not w_word:
                    continue

                # Lead-in silence if there's a gap between words
                lead_in = w_start - prev_end
                if lead_in > 0.05:
                    karaoke_text_parts.append(f"{{\\k{seconds_to_centiseconds(lead_in)}}}")

                dur_cs = seconds_to_centiseconds(max(0.05, w_end - w_start))
                karaoke_text_parts.append(f"{{{karaoke_tag}{dur_cs}}}{w_word} ")
                prev_end = w_end

            karaoke_text = "".join(karaoke_text_parts).rstrip()
            if not karaoke_text:
                karaoke_text = str(seg.get("text", "")).strip()

            lines.append(f"Dialogue: 0,{start_str},{end_str},Karaoke,,0,0,0,,{karaoke_text}")
        else:
            # Segment level fallback (clean text without karaoke split)
            clean_text = str(seg.get("text", "")).strip()
            total_dur_cs = seconds_to_centiseconds(max(0.1, seg_end - seg_start))
            lines.append(f"Dialogue: 0,{start_str},{end_str},Default,,0,0,0,,{{{karaoke_tag}{total_dur_cs}}}{clean_text}")

    return "\r\n".join(lines) + "\r\n"


def export_karaoke_video(
    audio_path: str,
    ass_path: str,
    output_mp4_path: str,
    background_color: str = "#0f172a",
    duration_s: Optional[float] = None,
    resolution: str = "1280x720",
    ffmpeg_binary: Optional[str] = None,
) -> bool:
    """
    Render a video using FFmpeg with hard-burned ASS karaoke subtitles over a clean background.
    """
    bin_path = ffmpeg_binary or find_system_or_bundled_ffmpeg()
    if not bin_path or not os.path.exists(bin_path):
        raise FileNotFoundError("FFmpeg executable not found. Cannot render MP4 video.")

    if not os.path.isfile(audio_path):
        raise FileNotFoundError(f"Audio file not found: {audio_path}")
    if not os.path.isfile(ass_path):
        raise FileNotFoundError(f"ASS subtitle file not found: {ass_path}")

    # Escape path for FFmpeg subtitles filter on Windows (forward slashes and escaped colon)
    escaped_ass = ass_path.replace("\\", "/").replace(":", "\\:")

    # Build lavfi color video source + audio + subtitles filter
    cmd = [
        bin_path,
        "-y",
        "-f", "lavfi",
        "-i", f"color=c={background_color}:s={resolution}:r=30",
        "-i", audio_path,
        "-vf", f"subtitles='{escaped_ass}'",
        "-c:v", "libx264",
        "-preset", "ultrafast",
        "-crf", "23",
        "-c:a", "aac",
        "-b:a", "192k",
        "-shortest",
        "-pix_fmt", "yuv420p",
        output_mp4_path,
    ]

    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=120)
    if proc.returncode != 0:
        raise RuntimeError(f"FFmpeg video export failed (exit {proc.returncode}): {proc.stderr[:400]}")

    return os.path.isfile(output_mp4_path) and os.path.getsize(output_mp4_path) > 1000
